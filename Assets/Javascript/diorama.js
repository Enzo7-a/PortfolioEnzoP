                pollen.set(i, x, height(x, z) + p.oy + Math.sin(t * p.sp * 1.3 + p.ph * 2) * 0.25, z, 0.045, [1, 0.95, 0.7], 0.35 + 0.35 * Math.sin(t * 1.7 + p.ph));
